# ==================== 工具函数 ====================

def _parse_mm(val) -> float:
    """解析 "220mm" 为 220.0"""
    if isinstance(val, (int, float)):
        return float(val)
    if isinstance(val, str):
        return float(val.replace('mm', '').replace('kg', '').replace('kN', '').strip())
    return 0.0


def _calc_bbox(outer_d: float = 100, length: float = 100, thickness: float = 50) -> dict:
    """计算包围盒"""
    return {
        'x': max(length, outer_d),
        'y': max(outer_d, thickness),
        'z': max(outer_d, thickness),
    }


